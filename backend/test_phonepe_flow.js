import mongoose from "mongoose";
import dotenv from "dotenv";
import crypto from "crypto";

dotenv.config({ path: "./.env" });

const API_URL = "http://localhost:5001/api";
const SALT_KEY = process.env.PHONEPE_SALT_KEY || "96434309-7796-489d-8924-ab56988a6076";
const SALT_INDEX = process.env.PHONEPE_SALT_INDEX || "1";
const MERCHANT_ID = process.env.PHONEPE_MERCHANT_ID || "PGTESTPAYUAT86";

function createWebhookPayload({ merchantTransactionId, transactionId, amount, state = "COMPLETED", code = "PAYMENT_SUCCESS" }) {
  const payload = {
    success: state === "COMPLETED",
    code,
    message: state === "COMPLETED" ? "Payment successful" : "Payment failed",
    data: {
      merchantId: MERCHANT_ID,
      merchantTransactionId,
      transactionId: transactionId || `T_TEST_${Date.now()}`,
      amount,
      state,
      responseCode: code,
      paymentInstrument: {
        type: "UPI",
        utr: "123456789012"
      }
    }
  };

  const base64Response = Buffer.from(JSON.stringify(payload)).toString("base64");
  const hash = crypto.createHash("sha256").update(base64Response + SALT_KEY).digest("hex");
  const xVerify = `${hash}###${SALT_INDEX}`;

  return {
    body: { response: base64Response },
    xVerify,
    payload
  };
}

async function runTestSuite() {
  console.log("==================================================");
  console.log("🚀 STARTING PHONEPE INTEGRATION TEST SUITE");
  console.log("==================================================");

  await mongoose.connect(process.env.MONGODB_URI);
  console.log("Connected to MongoDB.");

  const GarbaEvent = (await import("./src/models/GarbaEvent.js")).default;
  const GarbaPass = (await import("./src/models/GarbaPass.js")).default;
  const GarbaOrder = (await import("./src/models/GarbaOrder.js")).default;
  const GarbaTicket = (await import("./src/models/GarbaTicket.js")).default;

  // Find active event and pass
  const event = await GarbaEvent.findOne({ slug: "garba-night-2026" });
  if (!event) throw new Error("Event not found!");
  const pass = await GarbaPass.findOne({ event: event._id });
  if (!pass) throw new Error("Pass not found!");

  console.log(`Using Event: ${event.name} (${event._id})`);
  console.log(`Using Pass: ${pass.name} (Price: ₹${pass.price})`);

  let testsPassed = 0;
  let totalTests = 0;

  function assert(condition, testName) {
    totalTests++;
    if (condition) {
      console.log(`✅ PASS: ${testName}`);
      testsPassed++;
    } else {
      console.error(`❌ FAIL: ${testName}`);
      throw new Error(`Test failed: ${testName}`);
    }
  }

  // ----------------------------------------------------
  // TEST 1: Customer Order Creation -> PhonePe Pay Initiation
  // ----------------------------------------------------
  console.log("\n--- TEST 1: Create Order & Initiate PhonePe Payment ---");
  const orderRes = await fetch(`${API_URL}/orders`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      eventId: event._id,
      customerName: "Rahul Sharma",
      customerPhone: "9876543210",
      customerEmail: "rahul@example.com",
      items: [{ passId: pass._id, quantity: 2 }]
    })
  });
  const orderData = await orderRes.json();
  assert(orderRes.ok && orderData.success, "Order created successfully");
  const order1 = orderData.data.order;
  assert(order1.paymentStatus === "PENDING", "Initial order status is PENDING");
  assert(order1.totalAmount === pass.price * 2, "Backend calculated exact total amount");

  const initRes = await fetch(`${API_URL}/payments/create-order`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ orderId: order1._id })
  });
  const initData = await initRes.json();
  assert(initRes.ok && initData.success, "PhonePe payment initiated");
  assert(Boolean(initData.data.checkoutUrl), "Checkout URL generated by PhonePe");
  assert(Boolean(initData.data.merchantTransactionId), "Unique merchantTransactionId generated");
  assert(initData.data.gateway === "PHONEPE", "Payment gateway is PHONEPE");

  const order1Updated = await GarbaOrder.findById(order1._id);
  assert(order1Updated.paymentStatus === "PROCESSING", "Order transitioned to PROCESSING");
  assert(order1Updated.paymentOrderId === initData.data.merchantTransactionId, "merchantTransactionId saved on order");

  // ----------------------------------------------------
  // TEST 2: S2S Webhook Invalid Signature Rejection
  // ----------------------------------------------------
  console.log("\n--- TEST 2: Invalid Webhook Signature Rejection ---");
  const webhookData1 = createWebhookPayload({
    merchantTransactionId: initData.data.merchantTransactionId,
    transactionId: "T_TEST_101",
    amount: Math.round(order1.totalAmount * 100),
    state: "COMPLETED"
  });

  const fakeSigRes = await fetch(`${API_URL}/payments/phonepe/webhook`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-VERIFY": "fake_signature_hash###1"
    },
    body: JSON.stringify(webhookData1.body)
  });
  assert(fakeSigRes.status === 400, "Forged signature rejected with HTTP 400");
  const order1StillProcessing = await GarbaOrder.findById(order1._id);
  assert(order1StillProcessing.paymentStatus === "PROCESSING", "Order not marked paid on forged signature");

  // ----------------------------------------------------
  // TEST 3: S2S Webhook Incorrect Amount Rejection
  // ----------------------------------------------------
  console.log("\n--- TEST 3: Webhook Amount Mismatch Protection ---");
  const badAmountWebhook = createWebhookPayload({
    merchantTransactionId: initData.data.merchantTransactionId,
    transactionId: "T_TEST_BAD_AMT",
    amount: 100, // Only 100 paise instead of full amount
    state: "COMPLETED"
  });

  const badAmtRes = await fetch(`${API_URL}/payments/phonepe/webhook`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-VERIFY": badAmountWebhook.xVerify
    },
    body: JSON.stringify(badAmountWebhook.body)
  });
  assert(badAmtRes.status === 500 || badAmtRes.status === 400, "Mismatched payment amount rejected");
  const order1StillProcessing2 = await GarbaOrder.findById(order1._id);
  assert(order1StillProcessing2.paymentStatus === "PROCESSING", "Order remains unpaid on amount mismatch");

  // ----------------------------------------------------
  // TEST 4: Genuine S2S Webhook Payment Confirmation & Ticket Generation
  // ----------------------------------------------------
  console.log("\n--- TEST 4: Valid S2S Webhook -> Order PAID & Tickets Generated ---");
  const genuineWebhook = createWebhookPayload({
    merchantTransactionId: initData.data.merchantTransactionId,
    transactionId: "T_PHONEPE_GENUINE_001",
    amount: Math.round(order1.totalAmount * 100),
    state: "COMPLETED"
  });

  const genuineRes = await fetch(`${API_URL}/payments/phonepe/webhook`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-VERIFY": genuineWebhook.xVerify
    },
    body: JSON.stringify(genuineWebhook.body)
  });
  const genuineJson = await genuineRes.json();
  assert(genuineRes.ok && genuineJson.success, "Genuine PhonePe webhook accepted with HTTP 200");

  const order1Paid = await GarbaOrder.findById(order1._id);
  assert(order1Paid.paymentStatus === "PAID", "Order paymentStatus is now PAID");
  assert(order1Paid.paymentId === "T_PHONEPE_GENUINE_001", "PhonePe paymentId stored");
  assert(Boolean(order1Paid.paidAt), "Order paidAt timestamp recorded");
  assert(order1Paid.paymentGateway === "PHONEPE", "Order paymentGateway is PHONEPE");

  const tickets = await GarbaTicket.find({ order: order1._id }).select("+qrToken");
  assert(tickets.length === 2, `Exactly 2 tickets generated for quantity 2 (found ${tickets.length})`);
  assert(tickets[0].status === "ACTIVE" && tickets[1].status === "ACTIVE", "Generated tickets are ACTIVE");
  assert(tickets[0].ticketNumber !== tickets[1].ticketNumber, "Unique ticketNumbers generated");
  assert(Boolean(tickets[0].qrToken) && tickets[0].qrToken.length >= 32, "Cryptographically secure qrToken generated");

  // ----------------------------------------------------
  // TEST 5: Duplicate Webhook Idempotency Check
  // ----------------------------------------------------
  console.log("\n--- TEST 5: Duplicate Webhook Delivery (Idempotency) ---");
  const duplicateRes = await fetch(`${API_URL}/payments/phonepe/webhook`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-VERIFY": genuineWebhook.xVerify
    },
    body: JSON.stringify(genuineWebhook.body)
  });
  assert(duplicateRes.ok, "Duplicate webhook returns HTTP 200");
  const ticketsAfterDup = await GarbaTicket.find({ order: order1._id });
  assert(ticketsAfterDup.length === 2, "No duplicate tickets generated on repeated webhook");

  // ----------------------------------------------------
  // TEST 6: Atomic Ticket Check-in (ACTIVE -> USED) & Scanner
  // ----------------------------------------------------
  console.log("\n--- TEST 6: Atomic Ticket Check-in & Scanner Protection ---");
  const ticket1 = await GarbaTicket.findById(tickets[0]._id).select("+qrToken");

  const GarbaAdmin = (await import("./src/models/GarbaAdmin.js")).default;
  const admin = await GarbaAdmin.findOne({ isActive: true });
  const jwt = (await import("jsonwebtoken")).default;
  const adminToken = admin ? jwt.sign({ adminId: admin._id }, process.env.JWT_SECRET) : "";

  const scanHeaders = {
    "Content-Type": "application/json",
    ...(adminToken ? { Authorization: `Bearer ${adminToken}` } : {})
  };

  const scanRes1 = await fetch(`${API_URL}/admin/scanner/scan`, {
    method: "POST",
    headers: scanHeaders,
    body: JSON.stringify({ qrToken: ticket1.qrToken })
  });
  const scanData1 = await scanRes1.json();
  assert(scanRes1.ok && scanData1.success, "First ticket scan succeeds");
  assert(scanData1.result === "SUCCESS", "Result is SUCCESS");

  const scannedTicketInDb = await GarbaTicket.findById(ticket1._id);
  assert(scannedTicketInDb.status === "USED", "Ticket status atomically transitioned to USED");
  assert(Boolean(scannedTicketInDb.checkedInAt), "checkedInAt recorded");

  // Attempt duplicate scan
  const scanRes2 = await fetch(`${API_URL}/admin/scanner/scan`, {
    method: "POST",
    headers: scanHeaders,
    body: JSON.stringify({ qrToken: ticket1.qrToken })
  });
  const scanData2 = await scanRes2.json();
  assert(scanRes2.status === 409, "Second scan rejected with HTTP 409");
  assert(scanData2.result === "ALREADY_USED", "Result is ALREADY_USED");

  // ----------------------------------------------------
  // TEST 7: Failed / Cancelled Payment -> Release Inventory & No Tickets
  // ----------------------------------------------------
  console.log("\n--- TEST 7: Failed/Cancelled Payment (No Tickets, Release Inventory) ---");
  const failOrderRes = await fetch(`${API_URL}/orders`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      eventId: event._id,
      customerName: "Failed Customer",
      customerPhone: "9123456789",
      items: [{ passId: pass._id, quantity: 1 }]
    })
  });
  const failOrder = (await failOrderRes.json()).data.order;

  const failInit = await (await fetch(`${API_URL}/payments/create-order`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ orderId: failOrder._id })
  })).json();

  const failedWebhook = createWebhookPayload({
    merchantTransactionId: failInit.data.merchantTransactionId,
    transactionId: "T_FAILED_TXN",
    amount: Math.round(failOrder.totalAmount * 100),
    state: "FAILED",
    code: "PAYMENT_DECLINED"
  });

  const failWebhookRes = await fetch(`${API_URL}/payments/phonepe/webhook`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "X-VERIFY": failedWebhook.xVerify
    },
    body: JSON.stringify(failedWebhook.body)
  });
  assert(failWebhookRes.ok, "Failed payment webhook acknowledged");

  const failOrderInDb = await GarbaOrder.findById(failOrder._id);
  assert(failOrderInDb.paymentStatus === "FAILED", "Order status marked FAILED");

  const failedOrderTickets = await GarbaTicket.find({ order: failOrder._id });
  assert(failedOrderTickets.length === 0, "No tickets generated for failed payment");

  // ----------------------------------------------------
  // TEST 8: Expired Order Rejection
  // ----------------------------------------------------
  console.log("\n--- TEST 8: Expired Order Rejection ---");
  const expiredOrder = await GarbaOrder.create({
    orderNumber: `GP_EXP_${Date.now()}`,
    event: event._id,
    customerName: "Expired Customer",
    customerPhone: "9000000000",
    membersCount: 1,
    items: [{ pass: pass._id, passType: pass.passType, passName: pass.name, membersCount: 1, quantity: 1, price: 100, subtotal: 100 }],
    subtotal: 100,
    totalAmount: 100,
    paymentStatus: "PENDING",
    expiresAt: new Date(Date.now() - 60000) // Expired 1 min ago
  });

  const expiredRes = await fetch(`${API_URL}/payments/create-order`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ orderId: expiredOrder._id })
  });
  assert(expiredRes.status === 400, "Expired order payment creation rejected with HTTP 400");
  const expJson = await expiredRes.json();
  assert(expJson.message.toLowerCase().includes("expired"), "Error message states order has expired");

  // ----------------------------------------------------
  // TEST 9: Reconciliation Endpoint & Refresh Flow
  // ----------------------------------------------------
  console.log("\n--- TEST 9: Server-side Payment Reconciliation ---");
  const reconcileRes = await fetch(`${API_URL}/payments/reconcile`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ orderId: order1._id })
  });
  const reconcileJson = await reconcileRes.json();
  assert(reconcileRes.ok && reconcileJson.success, "Reconciliation endpoint returns success");
  assert(reconcileJson.data.order.paymentStatus === "PAID", "Reconciled order confirms PAID status to frontend");

  console.log("\n==================================================");
  console.log(`🎉 ALL ${testsPassed} OF ${totalTests} TESTS PASSED SUCCESSFULLY!`);
  console.log("==================================================");

  await mongoose.disconnect();
}

runTestSuite().catch(err => {
  console.error("FATAL TEST ERROR:", err);
  process.exit(1);
});
